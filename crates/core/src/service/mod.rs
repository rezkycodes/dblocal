/// Result of a service call that must keep its module-local stable `DBL-xxxx`
/// code.
///
/// The lifecycle calls above return [`crate::error::Result`], whose variants own
/// fixed codes. The admin, update and client calls delegate to modules that own
/// their own code ranges (`DBL-81xx`, `DBL-80xx`, `DBL-83xx`); returning
/// [`UserFacingError`] keeps those codes instead of flattening them into
/// `DblError`'s generic ones.
pub type ServiceResult<T> = std::result::Result<T, UserFacingError>;

/// Builds the "not available in this build" default for a front-end that has
/// not implemented a newer method.
fn not_implemented<T>() -> ServiceResult<T> {
    Err(UserFacingError::new(
        crate::error::CODE_NOT_IMPLEMENTED,
        crate::strings::ERR_NOT_IMPLEMENTED,
    ))
}

/// One newer release, as a front-end renders it.
///
/// Immutable value type: no secrets and no paths from release JSON, only the
/// bounded fields the UI shows.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AvailableUpdateView {
    /// Semantic version of the release.
    pub version: String,
    /// Release tag as GitHub reports it.
    pub tag: String,
    /// Sanitized, bounded release notes.
    pub release_notes: String,
    /// Platform-matching asset name, for diagnostics.
    pub asset_name: String,
    /// Declared asset size in bytes.
    pub size_bytes: u64,
    /// Whether this install can self-update (`InstallKind::can_self_update`).
    pub can_self_update: bool,
}

/// Answer to "is there a newer DBLocal?" — the read model of `F-PKG-05` AC1.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UpdateStatus {
    /// The running version that was compared.
    pub current: String,
    /// The newer release, when one is available.
    pub available: Option<AvailableUpdateView>,
    /// How this binary was installed, which decides whether applying is allowed.
    pub install_kind: crate::update::InstallKind,
    /// Where the user must update instead, when self-update is refused
    /// (`F-PKG-05` AC2).
    pub package_manager_hint: Option<String>,
}

/// Identifier of a long-running operation, such as an install or a start.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct OperationId(String);

impl OperationId {
    /// Wraps an id generated by the service.
    pub fn new(value: impl Into<String>) -> Self {
        Self(value.into())
    }

    /// Borrowed string form.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl fmt::Display for OperationId {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(&self.0)
    }
}

/// Coarse-grained stage of a long-running operation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
#[non_exhaustive]
pub enum OperationStage {
    /// The operation is queued and has not started yet.
    Queued,
    /// The runtime is being downloaded.
    Downloading,
    /// The checksum is being verified.
    Verifying,
    /// The archive is being extracted.
    Extracting,
    /// The engine data directory is being initialised.
    Initializing,
    /// The engine process is starting.
    Starting,
    /// The operation completed successfully.
    Done,
    /// The operation failed.
    Failed,
}

impl OperationStage {
    /// Stable identifier for logs and events.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Queued => "queued",
            Self::Downloading => "downloading",
            Self::Verifying => "verifying",
            Self::Extracting => "extracting",
            Self::Initializing => "initializing",
            Self::Starting => "starting",
            Self::Done => "done",
            Self::Failed => "failed",
        }
    }
}

/// How a connection string should be rendered.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
#[non_exhaustive]
pub enum UriFormat {
    /// A bare URI, ready to paste into a client.
    #[default]
    Uri,
    /// A block of framework-style environment variables.
    DotEnv,
}

/// Event stream emitted by a [`DblService`].
#[derive(Debug, Clone, PartialEq, Eq)]
#[non_exhaustive]
pub enum ServiceEvent {
    /// One instance changed and its full view is ready to re-render.
    ///
    /// Carrying the whole [`InstanceView`] keeps the UI from having to fetch the
    /// row again after every status change.
    InstanceChanged {
        /// The instance after the change.
        view: InstanceView,
    },
    /// A long-running operation moved to a new stage.
    OperationProgress {
        /// Operation that progressed.
        id: OperationId,
        /// New stage.
        stage: OperationStage,
    },
    /// Download progress sample.
    DownloadProgress {
        /// Operation that is downloading.
        id: OperationId,
        /// Latest sample.
        progress: DownloadProgress,
    },
    /// A long-running operation finished, successfully or not.
    OperationFinished {
        /// Operation that finished.
        id: OperationId,
        /// Outcome, carrying a stable code and an optional start diagnosis.
        result: Result<(), UserFacingError>,
    },
    /// An instance no longer exists: deleted, rolled back after a failed
    /// create, or cleaned up after an interrupted create.
    ///
    /// `InstanceChanged` cannot carry this (there is no view left), so without
    /// it a consumer keeps showing a row that is gone. Consumers drop the row
    /// and any tab or log watcher for `id`.
    InstanceRemoved {
        /// The instance that is gone.
        id: InstanceId,
    },
    /// A stop had to escalate to a forced kill because the engine ignored the
    /// graceful shutdown within the grace period (PRD `F-INS-03` AC3: the user
    /// is told it was a forced stop). Emitted once, before the final
    /// `InstanceChanged` that carries the `Stopped` view.
    StopForced {
        /// The instance that was force-killed.
        id: InstanceId,
    },
    /// The catalog was refreshed or its freshness changed.
    CatalogUpdated {
        /// Freshness of the snapshot now in use.
        status: crate::model::CatalogStatus,
    },
    /// New lines arrived for an instance being watched.
    ///
    /// Only emitted while a watcher is enabled through
    /// [`DblService::watch_logs`]: live logs are opt-in so an idle GUI does no
    /// extra file I/O (PRD `F-LOG-01` AC1).
    LogLines {
        /// Instance the lines belong to.
        id: InstanceId,
        /// Appended lines, oldest first.
        lines: Vec<String>,
    },
    /// The list of databases or users for one instance changed, so the
    /// Databases tab (`F-DBU-01` AC2) re-reads it.
    ///
    /// Emitted after a create/drop database, a created user or a reset that
    /// changed the superuser credential. It carries no rows: the consumer
    /// re-reads through [`DblService::list_databases`] / [`DblService::list_users`],
    /// so a password can never ride an event.
    AdminChanged {
        /// Instance whose admin view is stale.
        id: InstanceId,
    },
    /// An update check finished and the result is ready to render (`F-PKG-05`).
    UpdateChecked {
        /// Newer version, or `None` when the running version is current.
        version: Option<String>,
        /// Whether this install may self-update; when false the UI points at the
        /// package manager instead.
        can_self_update: bool,
    },
    /// The config file of one instance changed (`F-CFG-01`), so the Config tab
    /// re-reads it through [`DblService::config_view`].
    ///
    /// Carries no content: a config file can hold a secret (`requirepass`) and an
    /// event must never carry one.
    ConfigChanged {
        /// Instance whose config changed.
        id: InstanceId,
    },
}

/// The only surface the GUI and the CLI use.
///
/// Every mutating call is asynchronous and non-blocking from the caller's
/// perspective: it returns quickly with an [`OperationId`] or a result, and
/// progress is reported through [`DblService::subscribe`].
pub trait DblService: Send + Sync + 'static {
    /// Lists every instance, in a stable order.
    fn list_instances(&self) -> Result<Vec<InstanceView>>;

    /// Returns the catalog read model, already filtered for this platform.
    fn catalog(&self) -> Result<CatalogView>;

    /// Refreshes the catalog in the background, ignoring the TTL when `force`.
    fn refresh_catalog(&self, force: bool) -> Result<OperationId>;

    /// Validates a spec before the UI submits it.
    ///
    /// A port owned by another instance reports that instance by name, which
    /// PRD `F-PRT-01` AC3 requires the form to show.
    fn validate_spec(&self, spec: &InstanceSpec) -> Result<()>;

    /// Proposes the next free port for an engine, `5432`/`5433`/... in order.
    fn suggest_port(&self, engine: EngineKey) -> Result<Port>;

    /// Starts creating an instance. Progress arrives as events.
    fn create_instance(&self, spec: InstanceSpec) -> Result<OperationId>;

    /// Starts an instance.
    fn start_instance(&self, id: &InstanceId) -> Result<OperationId>;

    /// Stops an instance.
    fn stop_instance(&self, id: &InstanceId) -> Result<OperationId>;

    /// Deletes an instance, archiving or purging its data.
    fn delete_instance(&self, id: &InstanceId, mode: DeleteMode) -> Result<OperationId>;

    /// Moves an instance to another port and releases the old allocation.
    fn change_port(&self, id: &InstanceId, port: Port) -> Result<()>;

    /// Current size of an instance's data directory, for the delete dialog.
    fn data_size(&self, id: &InstanceId) -> Result<u64>;

    /// Toggles whether an instance starts with the app.
    fn set_autostart(&self, id: &InstanceId, enabled: bool) -> Result<()>;

    /// Cancels a long-running operation, if it can still be cancelled.
    fn cancel_operation(&self, id: &OperationId) -> Result<()>;

    /// Returns a connection URI or `.env` block. The value is secret because
    /// it may embed the password.
    fn connection_uri(&self, id: &InstanceId, format: UriFormat) -> Result<SecretString>;

    /// Returns the last `lines` of an instance log.
    fn tail_logs(&self, id: &InstanceId, lines: usize) -> Result<Vec<String>>;

    /// Enables or disables live log streaming for one instance.
    ///
    /// When enabled the service emits [`ServiceEvent::LogLines`] as new lines
    /// are appended. Enabling twice is idempotent; disabling an instance that
    /// was never watched is a no-op. This is the smallest API that satisfies
    /// `F-LOG-01` AC1 without the UI polling.
    fn watch_logs(&self, id: &InstanceId, enabled: bool) -> Result<()>;

    // --- Database & user administration (F-DBU-01..03) ----------------------

    /// Lists a running PostgreSQL instance's databases with owner and size.
    ///
    /// Engines without a database/user model — MySQL and MariaDB until their
    /// executor lands, and Valkey in v1 — return a typed "not supported for this
    /// engine yet" error, never an empty list.
    fn list_databases(&self, id: &InstanceId) -> ServiceResult<Vec<DatabaseInfo>> {
        let _ = id;
        not_implemented()
    }

    /// Creates a database with UTF-8 encoding (`F-DBU-01` AC2).
    fn create_database(&self, id: &InstanceId, name: &str) -> ServiceResult<()> {
        let _ = (id, name);
        not_implemented()
    }

    /// Drops a database. `force == false` refuses while a session is connected.
    fn drop_database(&self, id: &InstanceId, name: &str, force: bool) -> ServiceResult<()> {
        let _ = (id, name, force);
        not_implemented()
    }

    /// Lists login-capable roles of a running PostgreSQL instance.
    fn list_users(&self, id: &InstanceId) -> ServiceResult<Vec<UserInfo>> {
        let _ = id;
        not_implemented()
    }

    /// Creates a login role at `level` on `db` and returns its password exactly
    /// once (`F-DBU-02` AC2). The service never stores this password; the caller
    /// shows it once and discards it.
    fn create_user(
        &self,
        id: &InstanceId,
        name: &str,
        db: &str,
        level: PrivilegeLevel,
    ) -> ServiceResult<SecretString> {
        let _ = (id, name, db, level);
        not_implemented()
    }

    /// Resets the superuser password, persists it, and returns the new value
    /// once (`F-DBU-03`). On any failure the old password still works and the
    /// stored credential is unchanged (`F-DBU-03` AC2).
    fn reset_superuser_password(&self, id: &InstanceId) -> ServiceResult<SecretString> {
        let _ = id;
        not_implemented()
    }

    // --- Updates (F-PKG-05) -------------------------------------------------

    /// Checks GitHub Releases for a newer version, only when the caller asks.
    ///
    /// There is no timer and no startup check; the caller decides when to call
    /// this. The result carries the [`crate::update::InstallKind`] so a
    /// package-manager install can be pointed at its manager (`F-PKG-05` AC2).
    fn check_update(&self) -> ServiceResult<UpdateStatus> {
        not_implemented()
    }

    /// Downloads, verifies and applies an available update. Refused for an
    /// install kind that a package manager owns.
    fn apply_update(&self) -> ServiceResult<()> {
        not_implemented()
    }

    // --- Open in external client (F-OPN-01..02) -----------------------------

    /// The clients detected on this machine, cached for the process.
    ///
    /// `refresh` re-runs detection and replaces the cache, which is how the
    /// "Open in…" menu picks up an app installed after launch.
    fn detect_clients(&self, refresh: bool) -> ServiceResult<Vec<DetectedClient>> {
        let _ = refresh;
        not_implemented()
    }

    /// Opens `client` against `target`, returning the plan it used.
    ///
    /// `dry_run` returns the plan without launching, for `--dry-run`. The
    /// password is only ever placed in a private launcher script, never in the
    /// plan's argv/URL/command string.
    fn open_in_client(
        &self,
        id: &InstanceId,
        client: ClientKind,
        dry_run: bool,
    ) -> ServiceResult<LaunchPlan> {
        let _ = (id, client, dry_run);
        not_implemented()
    }

    // --- Config editor (F-CFG-01, F-CFG-02) ---------------------------------

    /// The editable settings of an instance, their defaults and the newest
    /// backup (`F-CFG-01` AC1). Never contains a secret value.
    fn config_view(&self, id: &InstanceId) -> ServiceResult<crate::config::ConfigView> {
        let _ = id;
        not_implemented()
    }

    /// Applies a batch of `key=value` settings atomically (`F-CFG-01` AC2/AC3).
    ///
    /// Every key must be editable and every value must validate before anything
    /// is written; one refused entry refuses the whole call. A backup of the
    /// current file is taken first. The change is for the next start, so the
    /// result is always `restart_required = true`.
    fn config_apply(
        &self,
        id: &InstanceId,
        changes: Vec<(String, String)>,
    ) -> ServiceResult<crate::config::ConfigApplied> {
        let _ = (id, changes);
        not_implemented()
    }

    /// Restores the newest backup of the config file (`F-CFG-01` AC3).
    fn config_restore(&self, id: &InstanceId) -> ServiceResult<()> {
        let _ = id;
        not_implemented()
    }

    /// The raw config file path, for "open in the OS editor" (`F-CFG-02` AC1).
    ///
    /// Opening the file is the caller's job through the existing `open`
    /// machinery; this only returns the path and never writes anything.
    fn config_raw_path(&self, id: &InstanceId) -> ServiceResult<std::path::PathBuf> {
        let _ = id;
        not_implemented()
    }

    /// Opens the raw config file in the OS default handler (`F-CFG-02` AC1).
    ///
    /// Launches `xdg-open`/`open`/`rundll32` detached, argv only, no shell, and
    /// returns the command it ran (so the CLI can print the path when the
    /// handler is unavailable). Refuses with `DBL-8607` when the file does not
    /// exist yet and `DBL-8608` when the handler could not be started.
    fn config_open_raw(
        &self,
        id: &InstanceId,
    ) -> ServiceResult<crate::config::OpenCommand> {
        let _ = id;
        not_implemented()
    }

    /// Lists every installed runtime.
    fn list_runtimes(&self) -> Result<Vec<Runtime>>;

    /// Removes an installed runtime, refusing while an instance still uses it.
    fn remove_runtime(&self, runtime: &str) -> Result<()>;

    /// Lists data directories kept by "delete, keep data".
    fn list_archives(&self) -> Result<Vec<ArchivedData>>;

    /// Permanently deletes one archive.
    fn purge_archive(&self, archive: &str) -> Result<()>;

    /// Subscribes to the service event stream.
    fn subscribe(&self) -> broadcast::Receiver<ServiceEvent>;
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{AuthMode, EngineKey, Instance, InstanceName, InstanceStatus};
    use std::time::SystemTime;

    fn spec() -> InstanceSpec {
        InstanceSpec::new(
            InstanceName::new("app-dev").expect("valid"),
            EngineKey::Postgresql,
            "18.7",
            Some(Port::new(5432).expect("valid")),
            AuthMode::Password,
        )
        .expect("valid spec")
    }

    #[test]
    fn view_reflects_the_instance() {
        let instance = Instance::new(
            &spec(),
            InstanceId::new(),
            InstanceStatus::Stopped,
            SystemTime::UNIX_EPOCH,
        );
        let view = InstanceView::from_instance(&instance);
        assert_eq!(view.name, "app-dev");
        assert_eq!(view.engine, EngineKey::Postgresql);
        assert_eq!(view.status, InstanceStatus::Stopped);
        assert_eq!(view.port.get(), 5432);
    }

    #[test]
    fn ids_and_stages_have_stable_strings() {
        let id = OperationId::new("op-1");
        assert_eq!(id.as_str(), "op-1");
        assert_eq!(id.to_string(), "op-1");
        assert_eq!(OperationStage::Downloading.as_str(), "downloading");
        assert_eq!(OperationStage::Done.as_str(), "done");
    }

    #[test]
    fn uri_format_defaults_to_uri() {
        assert_eq!(UriFormat::default(), UriFormat::Uri);
    }

    #[test]
    fn operation_finished_preserves_the_error_code() {
        let failure = ServiceEvent::OperationFinished {
            id: OperationId::new("op-2"),
            result: Err(crate::DblError::PortInUse { port: 5432 }.into()),
        };
        match failure {
            ServiceEvent::OperationFinished { result, .. } => {
                let err = result.expect_err("must be an error");
                assert_eq!(err.code, "DBL-1005");
                assert!(!err.message.is_empty());
                assert!(err.diagnosis.is_none());
            }
            other => panic!("unexpected {other:?}"),
        }
    }

    #[test]
    fn instance_changed_carries_the_full_view() {
        let instance = Instance::new(
            &spec(),
            InstanceId::new(),
            InstanceStatus::Running,
            SystemTime::UNIX_EPOCH,
        );
        let event = ServiceEvent::InstanceChanged {
            view: InstanceView::from_instance(&instance),
        };
        match event {
            ServiceEvent::InstanceChanged { view } => {
                assert_eq!(view.status, InstanceStatus::Running);
                assert_eq!(view.name, "app-dev");
            }
            other => panic!("unexpected {other:?}"),
        }
    }

    #[test]
    fn log_lines_event_is_shape_only() {
        let event = ServiceEvent::LogLines {
            id: InstanceId::new(),
            lines: vec!["a".into()],
        };
        assert!(matches!(event, ServiceEvent::LogLines { .. }));
    }
}
