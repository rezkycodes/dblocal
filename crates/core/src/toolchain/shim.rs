//! Generated launchers ("shims") for the active toolchain versions.
//!
//! A shim is a tiny launcher with the absolute target baked in. It is not a
//! resident process and changes nothing about the app's idle CPU/RSS. The shims
//! live in `<root>/bin` and are regenerated whenever the active version changes.
//!
//! * **Linux** writes a `sh` script (`exec "<install>/bin/php" "$@"`). The `php`
//!   shim also exports `PHP_INI_SCAN_DIR` pointing at DBLocal's `conf.d`, so the
//!   managed settings are always picked up.
//! * **Windows** writes a `.cmd` batch file that forwards arguments, propagates the
//!   exit code and is Ctrl-C friendly (`call` / `%*`).
//! * **Composer** runs the PHAR through the sibling `php` shim
//!   (`"<root>/bin/php" composer.phar "$@"`), so switching PHP never regenerates
//!   the Composer shim. With no active PHP it prints a clear error.
//!
//! Every generated file starts with a marker comment; removal checks that marker
//! first, so a shim DBLocal did not write is never deleted.

use std::path::{Path, PathBuf};

use crate::DblError;
use crate::platform::Os;
use crate::toolchain::catalog::ToolId;
use crate::toolchain::consts;
use crate::toolchain::fsops::ToolchainPaths;
use crate::toolchain::registry::ActiveVersion;

/// What generated a given shim.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum ShimTool {
    /// `php`.
    Php,
    /// `node`.
    Node,
    /// `npm`.
    Npm,
    /// `npx`.
    Npx,
    /// `composer`.
    Composer,
}

impl ShimTool {
    /// The file stem of the shim.
    pub const fn name(self) -> &'static str {
        match self {
            Self::Php => "php",
            Self::Node => "node",
            Self::Npm => "npm",
            Self::Npx => "npx",
            Self::Composer => "composer",
        }
    }

    /// Every shim the release generates, in a stable order.
    pub const fn all() -> [ShimTool; 5] {
        [Self::Php, Self::Node, Self::Npm, Self::Npx, Self::Composer]
    }

    fn for_tool(tool: ToolId) -> &'static [ShimTool] {
        match tool {
            ToolId::Php => &[ShimTool::Php],
            ToolId::Node => &[ShimTool::Node, ShimTool::Npm, ShimTool::Npx],
            ToolId::Composer => &[ShimTool::Composer],
        }
    }

    /// Relative path to the target executable inside the tool's install dir.
    pub fn relative_target(self, os: Os) -> String {
        match (self, os) {
            (Self::Php, Os::Windows) => "php.exe".to_owned(),
            (Self::Php, _) => "php".to_owned(),
            (Self::Node, Os::Windows) => "node.exe".to_owned(),
            (Self::Npm, Os::Windows) => "npm.cmd".to_owned(),
            (Self::Npx, Os::Windows) => "npx.cmd".to_owned(),
            (Self::Node | Self::Npm | Self::Npx, _) => format!("bin/{}", self.name()),
            (Self::Composer, _) => crate::toolchain::catalog::php_phar_file().to_owned(),
        }
    }
}

/// Renders the script text for one shim.
///
/// `install_dir` is the absolute install root of the active version; `php_ini_dir`
/// is the managed `conf.d` for the php shim; `php_shim` is the sibling php launcher
/// the composer shim delegates to. All paths are quoted so spaces are safe.
pub fn render(
    shim: ShimTool,
    os: Os,
    install_dir: &Path,
    php_ini_dir: &Path,
    php_shim: &Path,
) -> String {
    match os {
        Os::Windows => render_cmd(shim, install_dir, php_ini_dir, php_shim),
        _ => render_sh(shim, install_dir, php_ini_dir, php_shim),
    }
}

fn render_sh(shim: ShimTool, install_dir: &Path, php_ini_dir: &Path, php_shim: &Path) -> String {
    let mut script = String::from("#!/bin/sh\n");
    script.push_str(consts::SHIM_MARKER);
    script.push('\n');
    script.push_str(
        "# Generated by DBLocal; do not edit. It is rewritten when the active version changes.\n",
    );
    match shim {
        ShimTool::Php => {
            let target = install_dir.join(shim.relative_target(Os::Linux));
            script.push_str(&format!(
                "PHP_INI_SCAN_DIR={}\nexport PHP_INI_SCAN_DIR\n",
                shell_quote(&php_ini_dir.display().to_string())
            ));
            script.push_str(&format!(
                "exec {} \"$@\"\n",
                shell_quote(&target.display().to_string())
            ));
        }
        ShimTool::Node | ShimTool::Npm | ShimTool::Npx => {
            let target = install_dir.join(shim.relative_target(Os::Linux));
            script.push_str(&format!(
                "exec {} \"$@\"\n",
                shell_quote(&target.display().to_string())
            ));
        }
        ShimTool::Composer => {
            let phar = install_dir.join(shim.relative_target(Os::Linux));
            script.push_str(
                "# Run the PHAR through the sibling php shim so switching PHP needs no rewrite.\n",
            );
            script.push_str(&format!(
                "if [ ! -x {php} ]; then\n  echo 'composer: no active PHP. Run `dblocal toolchain use php <version>` first.' >&2\n  exit 1\nfi\n",
                php = shell_quote(&php_shim.display().to_string())
            ));
            script.push_str(&format!(
                "exec {} {} \"$@\"\n",
                shell_quote(&php_shim.display().to_string()),
                shell_quote(&phar.display().to_string())
            ));
        }
    }
    script
}

fn render_cmd(shim: ShimTool, install_dir: &Path, php_ini_dir: &Path, php_shim: &Path) -> String {
    let mut script = String::from("@echo off\r\n");
    script.push_str(consts::SHIM_MARKER_CMD);
    script.push_str("\r\n");
    script.push_str("rem Generated by DBLocal; do not edit. It is rewritten when the active version changes.\r\n");
    match shim {
        ShimTool::Php => {
            let target = install_dir.join(shim.relative_target(Os::Windows));
            script.push_str(&format!(
                "set \"PHP_INI_SCAN_DIR={}\"\r\n",
                php_ini_dir.display()
            ));
            script.push_str(&format!("\"{}\" %*\r\n", target.display()));
            script.push_str("exit /b %ERRORLEVEL%\r\n");
        }
        ShimTool::Node | ShimTool::Npm | ShimTool::Npx => {
            let target = install_dir.join(shim.relative_target(Os::Windows));
            script.push_str(&format!("call \"{}\" %*\r\n", target.display()));
            script.push_str("exit /b %ERRORLEVEL%\r\n");
        }
        ShimTool::Composer => {
            let phar = install_dir.join(shim.relative_target(Os::Windows));
            script.push_str(&format!(
                "if not exist \"{}\" (\r\n  echo composer: no active PHP. Run `dblocal toolchain use php ^<version^>` first. 1>&2\r\n  exit /b 1\r\n)\r\n",
                php_shim.display()
            ));
            script.push_str(&format!(
                "call \"{}\" \"{}\" %*\r\n",
                php_shim.display(),
                phar.display()
            ));
            script.push_str("exit /b %ERRORLEVEL%\r\n");
        }
    }
    script
}

/// Single-quotes a path for `sh`, escaping embedded single quotes.
fn shell_quote(value: &str) -> String {
    let mut out = String::from("'");
    for ch in value.chars() {
        if ch == '\'' {
            out.push_str("'\\''");
        } else {
            out.push(ch);
        }
    }
    out.push('\'');
    out
}

/// Regenerates every shim for the given active versions.
///
/// Shims for a tool with no active version are removed (if DBLocal wrote them).
/// This is idempotent: applying the same registry twice rewrites the same bytes.
/// A failure on one tool does not abort refreshing the remaining tools.
pub fn refresh(
    paths: &ToolchainPaths,
    os: Os,
    registry: &crate::toolchain::registry::Registry,
) -> crate::Result<()> {
    let shims_dir = paths.shims_dir();
    let mut first_err: Option<DblError> = None;
    for tool in ToolId::all() {
        match registry.get(tool) {
            Some(active) => {
                if let Err(err) = write_for_tool(paths, os, active) {
                    first_err.get_or_insert(err);
                }
            }
            None => remove_for_tool(&shims_dir, os, tool),
        }
    }
    match first_err {
        Some(err) => Err(err),
        None => Ok(()),
    }
}

/// Writes the shim(s) for one active tool.
fn write_for_tool(paths: &ToolchainPaths, os: Os, active: &ActiveVersion) -> crate::Result<()> {
    let install_dir = paths.install_dir(active.tool(), active.version(), active.profile());
    let php_ini_dir = paths.php_conf_dir(ToolId::Php);
    let php_shim = paths.shim_path(ShimTool::Php.name(), os);

    // Always write the Composer shim even if no PHP is active yet: the shim
    // itself prints a clear runtime error when PHP is missing, and starts
    // working as soon as a PHP version is activated.
    for shim in ShimTool::for_tool(active.tool()) {
        let text = render(*shim, os, &install_dir, &php_ini_dir, &php_shim);
        let path = paths.shim_path(shim.name(), os);
        write_shim(&path, text.as_bytes())?;
    }
    Ok(())
}

/// Removes every shim of one tool, checking the marker first.
fn remove_for_tool(shims_dir: &Path, os: Os, tool: ToolId) {
    for shim in ShimTool::for_tool(tool) {
        let file = match os {
            Os::Windows => format!("{}.cmd", shim.name()),
            _ => shim.name().to_owned(),
        };
        let path = shims_dir.join(file);
        remove_shim_if_ours(&path);
    }
}

/// Removes a shim only when it carries DBLocal's marker.
///
/// Returns whether anything was removed. A file DBLocal did not write is left
/// untouched, so a user's own `php` in the shims dir is never deleted.
pub fn remove_shim_if_ours(path: &Path) -> bool {
    let Ok(bytes) = std::fs::read(path) else {
        return false;
    };
    let text = String::from_utf8_lossy(&bytes);
    let ours = text.contains(consts::SHIM_MARKER) || text.contains(consts::SHIM_MARKER_CMD);
    if !ours {
        return false;
    }
    std::fs::remove_file(path).is_ok()
}

/// Removes one tool's shim(s) by name, used when its active version is cleared.
pub fn remove_for(paths: &ToolchainPaths, os: Os, tool: ToolId) {
    remove_for_tool(&paths.shims_dir(), os, tool);
}

/// Writes a shim atomically with the executable bit on Unix.
fn write_shim(path: &Path, contents: &[u8]) -> crate::Result<()> {
    crate::fsutil::write_executable_file_atomic(path, contents)
        .map_err(|source| DblError::Io { source })
}

/// Reads a shim's first line, for doctor checks and tests.
pub fn shim_target(path: &Path) -> Option<PathBuf> {
    let text = std::fs::read_to_string(path).ok()?;
    for line in text.lines() {
        let trimmed = line.trim();
        if let Some(rest) = trimmed.strip_prefix("exec ") {
            let first = rest.split_whitespace().next()?;
            return Some(PathBuf::from(unquote(first)));
        }
        if let Some(after) = trimmed.strip_prefix('"') {
            // A .cmd target line: the first quoted path is the executable.
            if let Some(end) = after.find('"') {
                return Some(PathBuf::from(&after[..end]));
            }
        }
    }
    None
}

fn unquote(token: &str) -> String {
    token.trim_matches('\'').to_owned()
}

